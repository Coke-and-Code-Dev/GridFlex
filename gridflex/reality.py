"""Reality check: do GLASS's synthetic days look like Liander's real 2023 profiles? (idea.md 5.10)

For one category, month and level, build the typical working day of GLASS and of a Liander
profile, rescale both to the same mean, then compare the median shapes (correlation and mean
absolute difference) and keep the p10-p90 bands for the chart.

Shapes only: Liander's values are relative to each customer's peak, GLASS's are kW.
Limits worth saying out loud:
- GLASS was generated by a model trained on Liander smart-meter data, so agreement shows it
  reproduces that data; it is not an independent test.
- Working days are Monday-Friday; public holidays are not removed.
- Liander's profile is the whole 2023 customer group, GLASS is one consumption level.

Typical-day arrays run midnight to midnight: slot 0 is 00:00, slot 95 is 23:45.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import polars as pl

from gridflex.profiles import DEFAULT_DATA_DIR, N_SLOTS, load_condition

# Liander profiles used per GLASS category (idea.md 4.3). SBI 46 (wholesale) has no usable
# profile (no time series, and a warning), so category 008 falls back to the logistics K&O profile.
SOURCES_FOR_CATEGORY: dict[str, tuple[str, ...]] = {
    "009": ("52", "49", "KO_LOGISTIEK"),
    "008": ("KO_LOGISTIEK",),
}
CATEGORY_LABEL = {"009": "transport and storage sites", "008": "wholesale and retail sites"}
SOURCE_LABEL = {
    "49": "SBI 49 (land transport)",
    "52": "SBI 52 (warehousing and support activities)",
    "KO_LOGISTIEK": "the standard logistics profile",
}


@dataclass
class RealityCheck:
    sbi_code: str  # "49", "52" or a K&O profile name such as "KO_LOGISTIEK"
    correlation: float  # of the two typical-day median shapes
    mean_abs_diff: float  # on mean-rescaled profiles (both have mean 1.0)
    glass_band: np.ndarray  # (3, 96): p10, median, p90 of a typical working day, rescaled to mean 1.0
    liander_band: np.ndarray  # (3, 96): same; p10 and p90 rows are NaN when liander_has_band is False
    liander_has_band: bool = True  # False for a standard K&O profile (a single curve)
    category: str = ""
    month: str = ""
    level: int = 1
    n_glass_samples: int = 0
    n_glass_days: int = 0  # working days used
    n_liander_days: int = 0


LIANDER_YEAR = "2023"  # the one year Liander publishes; the GLASS month is matched by calendar month


def liander_path(sbi_code: str, month: str, data_dir: Path | None = None) -> Path:
    """Liander's file for the calendar month of `month` ("2024-03" and "2023-03" both give March 2023)."""
    return (data_dir or DEFAULT_DATA_DIR) / f"liander_sbi_{sbi_code}_{LIANDER_YEAR}-{month[5:7]}.parquet"


def _glass_typical_day(df: pl.DataFrame) -> tuple[np.ndarray, np.ndarray, int, int]:
    """(band (3, 96) kW, mean curve (96,) kW, working days, samples).

    Percentiles are taken across samples at each quarter-hour of each working day and then
    averaged over the days, the same way Liander's p10/median/p90 are built (across customers).
    """
    cols = sorted(c for c in df.columns if len(c) == 8 and c[2] == ":" and c[5] == ":")
    if len(cols) != N_SLOTS:
        raise ValueError(f"Expected {N_SLOTS} time columns, found {len(cols)}")
    df = df.with_columns(pl.col("date").str.to_date("%Y-%m-%d").alias("_d")).filter(pl.col("_d").dt.weekday() <= 5)
    if df.is_empty():
        raise ValueError("No working days in the GLASS condition")
    x = df.select(cols).to_numpy().astype(np.float64)
    days = df["_d"].to_numpy()
    bands, means = [], []
    for d in np.unique(days):
        day = x[days == d]  # (samples, 96)
        bands.append(np.percentile(day, [10, 50, 90], axis=0))
        means.append(day.mean(axis=0))
    return np.mean(bands, axis=0), np.mean(means, axis=0), len(bands), df["sample_id"].n_unique()


def _liander_typical_day(df: pl.DataFrame) -> tuple[np.ndarray, np.ndarray, bool, int]:
    """(band (3, 96), mean curve (96,), has_band, working days) of a Liander extract."""
    df = df.filter(pl.col("timestamp").dt.weekday() <= 5).with_columns(
        (pl.col("timestamp").dt.hour() * 4 + pl.col("timestamp").dt.minute() // 15).alias("_slot")
    )
    if df.is_empty():
        raise ValueError("No working days in the Liander extract")
    typical = df.group_by("_slot").agg(pl.col(c).mean() for c in ("p10", "median", "p90", "mean")).sort("_slot")
    if typical.height != N_SLOTS:
        raise ValueError(f"Expected {N_SLOTS} quarter-hours per day, found {typical.height}")
    mean = typical["mean"].to_numpy()
    has_band = typical["median"].null_count() == 0
    if has_band:
        band = np.vstack([typical[c].to_numpy() for c in ("p10", "median", "p90")])
    else:  # a standard profile: one curve, no spread
        band = np.vstack([np.full(N_SLOTS, np.nan), mean, np.full(N_SLOTS, np.nan)])
    return band, mean, has_band, df["timestamp"].dt.date().n_unique()


def compare(
    category: str, month: str, sbi_code: str, level: int = 1, data_dir: Path | None = None
) -> RealityCheck:
    """Compare GLASS (category, month, level) with Liander's 2023 profile `sbi_code` for the same calendar month."""
    glass = load_condition(category, month, level, data_dir)
    path = liander_path(sbi_code, month, data_dir)
    if not path.exists():
        raise FileNotFoundError(
            f"{path.name} not found in {path.parent}. "
            f"Run: python scripts/prepare_liander_sbi.py --sbi {sbi_code} --months {LIANDER_YEAR}-{month[5:7]}"
        )
    g_band, g_mean, n_days, n_samples = _glass_typical_day(glass)
    l_band, l_mean, has_band, l_days = _liander_typical_day(pl.read_parquet(path))

    # Same monthly mean: scale each source so its typical-day mean curve averages 1.0.
    g_band, l_band = g_band / g_mean.mean(), l_band / l_mean.mean()
    g_med, l_med = g_band[1], l_band[1]
    corr = float(np.corrcoef(g_med, l_med)[0, 1])
    return RealityCheck(
        sbi_code=sbi_code,
        correlation=corr,
        mean_abs_diff=float(np.abs(g_med - l_med).mean()),
        glass_band=g_band,
        liander_band=l_band,
        liander_has_band=has_band,
        category=category,
        month=month,
        level=level,
        n_glass_samples=n_samples,
        n_glass_days=n_days,
        n_liander_days=l_days,
    )


def compare_all(category: str, month: str, level: int = 1, data_dir: Path | None = None) -> list[RealityCheck]:
    """Every Liander source configured for the category that has an extract for the month."""
    return [
        compare(category, month, code, level, data_dir)
        for code in SOURCES_FOR_CATEGORY.get(category, ())
        if liander_path(code, month, data_dir).exists()
    ]


def summary(check: RealityCheck) -> str:
    """One plain sentence built only from the computed numbers (no LLM)."""
    strength = "closely" if check.correlation >= 0.9 else "broadly" if check.correlation >= 0.7 else "only loosely"
    sector = CATEGORY_LABEL.get(check.category, f"category {check.category} sites")
    source = SOURCE_LABEL.get(check.sbi_code, f"profile {check.sbi_code}")
    return (
        f"GLASS's synthetic {sector} follow the real 2023 Liander profile for {source} {strength} "
        f"(correlation {check.correlation:.2f}, mean difference {check.mean_abs_diff:.2f} of the average load)."
    )
